"""Generate independent bounded-arithmetic fixtures using Python integers."""
from fractions import Fraction
from math import gcd
from pathlib import Path
from random import Random

LIMIT = 1 << 511
CAPACITY = 1 << 512
rng = Random(0x4352494D45)


def number(value, indent):
    words = [(value >> (32 * i)) & 0xFFFFFFFF for i in range(16)]
    lines = [indent + "{ .word = {"]
    for i in range(0, 16, 4):
        lines.append(indent + "    " + ", ".join(
            f"0x{x:08x}U" for x in words[i:i + 4]) + ",")
    return lines + [indent + "} }"]


def rational(value, indent):
    lines = [indent + "{"]
    for n in (abs(value.numerator), value.denominator):
        part = number(n, indent + "    ")
        part[-1] += ","
        lines += part
    lines += [indent + "    " + ("true" if value < 0 else "false"),
              indent + "}"]
    return lines


def fits(n):
    return -LIMIT <= n < LIMIT


def add_allowed(a, b):
    g = gcd(a.denominator, b.denominator)
    an = a.numerator * (b.denominator // g)
    bn = b.numerator * (a.denominator // g)
    if not fits(an) or not fits(bn) or not fits(an + bn):
        return False
    h = gcd(abs(an + bn), g)
    return (a.denominator // g) * (b.denominator // h) < CAPACITY


def multiply_allowed(a, b):
    ga = gcd(abs(a.numerator), b.denominator)
    gb = gcd(abs(b.numerator), a.denominator)
    n = (a.numerator // ga) * (b.numerator // gb)
    d = (a.denominator // gb) * (b.denominator // ga)
    return fits(n) and d < CAPACITY


def generate(path):
    divisions = [(0, 1), (1, 1), (1, 2), (CAPACITY - 1, 1),
                 (CAPACITY - 1, CAPACITY - 1), (LIMIT, CAPACITY - 1)]
    for bits in (1, 31, 32, 63, 64, 65, 96, 127, 128, 129,
                 160, 192, 256, 384, 511):
        d = (1 << bits) | 1
        divisions.extend(((d - 1, d), (d, d), (CAPACITY - 1, d)))
    for bits in (72, 96, 128, 160, 256, 512):
        for _ in range(4):
            a = rng.getrandbits(bits) | (1 << (bits - 1))
            b = rng.getrandbits(bits - 1) | 1
            divisions.append((a, b))
    pairs = [(Fraction(0), Fraction(-1, LIMIT + 1)),
             (Fraction(LIMIT - 1), Fraction(1)),
             (Fraction(-LIMIT), Fraction(1)),
             (Fraction(-LIMIT), Fraction(-1)),
             (Fraction(LIMIT - 1), Fraction(2)),
             (Fraction(1, LIMIT + 1), Fraction(-1, LIMIT + 3)),
             (Fraction(1 << 509, (1 << 510) + 1),
              Fraction((1 << 510) + 1, 1 << 509))]
    for bits in (32, 64, 72, 96, 128, 160, 256, 510):
        for _ in range(4):
            a = Fraction(rng.getrandbits(bits), rng.getrandbits(bits) | 1)
            b = Fraction(-rng.getrandbits(bits), rng.getrandbits(bits) | 1)
            pairs.append((a, b))
    lines = ["/* SPDX-License-Identifier: BSD-3-Clause */",
             "/* Generated by crime-rational-vectors.py; Python exact integers. */",
             "typedef struct CrimeDivisionVector {",
             "    CrimeInteger a, b, quotient, remainder, gcd;",
             "} CrimeDivisionVector;", "",
             "static const CrimeDivisionVector crime_division_vectors[] = {"]
    for a, b in divisions:
        lines.append("    {")
        for n in (a, b, a // b, a % b, gcd(a, b)):
            part = number(n, "        ")
            part[-1] += ","
            lines += part
        lines.append("    },")
    lines += ["};", "", "typedef struct CrimeRationalVector {",
              "    CrimeRational a, b, sum, product;",
              "    bool add_allowed, multiply_allowed;",
              "} CrimeRationalVector;", "",
              "static const CrimeRationalVector crime_rational_vectors[] = {"]
    for a, b in pairs:
        add_ok, mul_ok = add_allowed(a, b), multiply_allowed(a, b)
        lines.append("    {")
        for value in (a, b, a + b if add_ok else Fraction(0),
                      a * b if mul_ok else Fraction(0)):
            part = rational(value, "        ")
            part[-1] += ","
            lines += part
        lines += ["        " + str(add_ok).lower() + ", " + str(mul_ok).lower(),
                  "    },"]
    lines += ["};", ""]
    path.write_text("\n".join(lines))
    print(len(divisions), "division/GCD and", len(pairs), "rational fixtures")


if __name__ == "__main__":
    generate(Path(__file__).with_suffix(".h"))
