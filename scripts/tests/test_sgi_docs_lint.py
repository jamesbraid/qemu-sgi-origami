"""Check scripts/ci/sgi-docs-lint.py against small page fixtures."""

import importlib.machinery
import importlib.util
import json
import tempfile
import unittest
from pathlib import Path

SOURCE = Path(__file__).resolve().parents[2]
_LOADER = importlib.machinery.SourceFileLoader(
    'sgi_docs_lint', str(SOURCE / 'scripts/ci/sgi-docs-lint.py'))
_SPEC = importlib.util.spec_from_loader('sgi_docs_lint', _LOADER)
lint = importlib.util.module_from_spec(_SPEC)
_LOADER.exec_module(lint)

GOOD_PART = """\
.. SPDX-License-Identifier: BSD-3-Clause

.. _sgi-demo:

=================
Demo: a test part
=================

Used in :ref:`sgi-ip30`.

The reset value is *inferred* and the width *unknown*. Code like
``*Inferred*`` and a *Glossary Term* are left alone.
"""


CATALOGUE = {
    'offerings': [
        {'product': 'origin200', 'display-name': 'Origin 200 (one-module)',
         'machine-options': 'origin200,topology=origin200'},
        {'product': 'onyx2', 'display-name': 'Onyx2 deskside',
         'machine-options': 'onyx2,topology=onyx2-deskside'},
    ],
    'topologies': [
        {'name': 'origin200-dual', 'product': 'origin200'},
        {'name': 'onyx2-deskside', 'product': 'onyx2'},
    ],
}


class DocsLintTests(unittest.TestCase):
    def run_lint(self, pages, listed=True, catalogue=CATALOGUE):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            if catalogue is not None:
                path = root / lint.CATALOGUE
                path.parent.mkdir(parents=True)
                path.write_text(json.dumps(catalogue))
            names = []
            for name, text in pages.items():
                path = root / lint.PAGES / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
                names.append(f'{lint.PAGES}/{name}')
            (root / 'LICENSE.origami.paths').write_text(
                '\n'.join(names if listed else []) + '\n')
            return lint.lint(root)

    def messages(self, pages, **kwargs):
        return '\n'.join(self.run_lint(pages, **kwargs))

    def test_good_part_page_is_clean(self):
        self.assertEqual(self.run_lint({'hardware/demo.rst': GOOD_PART}), [])

    def test_missing_spdx_and_label(self):
        text = GOOD_PART.replace('.. SPDX-License-Identifier: BSD-3-Clause',
                                 '.. nothing').replace('.. _sgi-demo:\n', '')
        out = self.messages({'hardware/demo.rst': text})
        self.assertIn('hardware/demo.rst:1: first line', out)
        self.assertIn('label must precede the title', out)

    def test_generated_comment_before_label_is_allowed(self):
        text = GOOD_PART.replace(
            '.. _sgi-demo:',
            '.. Generated by a script.\n   Edit the source.\n\n.. _sgi-demo:')
        self.assertEqual(self.run_lint({'hardware/demo.rst': text}), [])

    def test_part_titles(self):
        for title in ('Demo test part', 'Demo: a test part (IP30)',
                      'Demo (O2): a test part'):
            text = GOOD_PART.replace('Demo: a test part', title)
            out = self.messages({'hardware/demo.rst': text})
            self.assertIn('part title', out, title)

    def test_platform_title(self):
        text = GOOD_PART.replace('Demo: a test part', 'Fuel and others')
        self.assertIn('platform title',
                      self.messages({'ip35.rst': text}))
        text = GOOD_PART.replace('Demo: a test part', 'IP35: Fuel')
        self.assertEqual(self.run_lint({'ip35.rst': text}), [])

    def test_italic_near_misses(self):
        for bad in ('Inferred', 'Observed', 'approximated', 'estimated',
                    'assumed', 'establish', 'Software expectation'):
            text = GOOD_PART + f'\nThe width is *{bad}* here.\n'
            self.assertIn(f'*{bad}*', self.messages({'hardware/demo.rst': text}))

    def test_rating_variants(self):
        for bad in ('approximations', 'software expectations', 'inference',
                    'established as drawn', 'Unknown'):
            text = GOOD_PART + f'\nThe width is *{bad}* here.\n'
            self.assertIn(f'*{bad}*', self.messages({'hardware/demo.rst': text}))

    def test_ratings_in_directive_bodies_are_checked(self):
        table = GOOD_PART + (
            '\n.. list-table::\n   :header-rows: 1\n\n'
            '   * - Fact\n     - Rating\n'
            '   * - Reset value\n     - *Inferred* from the manual\n')
        out = self.messages({'hardware/demo.rst': table})
        self.assertIn('hardware/demo.rst:20: italic "*Inferred*"', out)
        seealso = GOOD_PART + (
            '\n.. seealso::\n\n   :doc:`other`, whose width is *Inferred*.\n')
        self.assertIn('italic "*Inferred*"',
                      self.messages({'hardware/demo.rst': seealso}))

    def test_literal_text_is_skipped(self):
        for block in ('.. code-block:: text\n\n   *Inferred* output\n',
                      'A dump::\n\n   *Inferred* output\n'):
            text = GOOD_PART + '\n' + block + '\nAfter it, *unknown*.\n'
            self.assertEqual(self.run_lint({'hardware/demo.rst': text}), [],
                             block)

    def test_used_in_required_except_overviews(self):
        text = GOOD_PART.replace('Used in :ref:`sgi-ip30`.', 'The part.')
        self.assertIn('begin with "Used in"',
                      self.messages({'hardware/demo.rst': text}))
        self.assertEqual(self.run_lint({'hardware/graphics.rst': text}), [])

    def test_roadmap_phrases(self):
        for bad in ('The decoder is not yet implemented.',
                    'The FIFO will be modelled later.',
                    'Wrapping will be supported.',
                    'Wrapping is planned.', 'Use a stub for now.',
                    'Covered in a later page.', 'Reads are yet to be wired.',
                    'The model does not support it yet.', 'TODO: widths.'):
            text = GOOD_PART + f'\n{bad}\n'
            out = self.messages({'hardware/demo.rst': text})
            self.assertIn('reads as a plan', out, bad)

    def test_roadmap_phrase_reports_the_wrapped_line(self):
        text = GOOD_PART + '\nThe first line\nwraps, and then the\nmodel will be\nmodelled.\n'
        self.assertIn('hardware/demo.rst:16: "will be modelled"',
                      self.messages({'hardware/demo.rst': text}))

    def test_roadmap_phrases_allowed_where_not_a_plan(self):
        for ok in ('An interrupt not yet delivered stays pending.',
                   'The sheet says "will be erased\nto read FFH".',
                   'The ``will be`` field is read back.',
                   'A request not yet acknowledged is repeated.',
                   'Writes to this bit will be ignored.',
                   'Reset will be released by the host.',
                   'The interrupt is not yet known to the CPU.',
                   'The status is not yet available to software.',
                   'The word is not yet decoded when the read starts.',
                   'The transfer is not yet done.',
                   'The word is not yet written by software.'):
            text = GOOD_PART + f'\n{ok}\n'
            self.assertEqual(self.run_lint({'hardware/demo.rst': text}), [], ok)
        block = GOOD_PART + '\n.. code-block:: text\n\n   will be TODO\n'
        self.assertEqual(self.run_lint({'hardware/demo.rst': block}), [])

    def warn(self, body):
        return lint.warn_page('hardware/demo.rst', GOOD_PART + '\n' + body)

    def test_hex_value_without_rating_warns(self):
        for bad in ('The register reads ``0x0015`` after reset.',
                    'The reset value is ``0x80``, as the PROM leaves it.',
                    'A read of the status word returns 0x1e000000.'):
            out = self.warn(bad + '\n')
            self.assertEqual(len(out), 1, bad)
            self.assertIn('hardware/demo.rst:14: warning:', out[0])

    def test_hex_value_with_rating_or_citation_is_quiet(self):
        for ok in ('The register reads ``0x0015`` after reset, *observed*.',
                   'The reset value is ``0x80`` (:src:`some-id p. 4`).',
                   'The register reads ``0x0015`` after\nreset, *inferred*.',
                   'Offset ``0x10`` is the base.',
                   'The model reads back what was written.'):
            self.assertEqual(self.warn(ok + '\n'), [], ok)

    def test_hex_value_in_table_row_or_literal_is_quiet(self):
        table = ('.. list-table::\n\n   * - Reset value\n     - reads '
                 '``0x80``\n')
        self.assertEqual(self.warn(table), [])
        self.assertEqual(self.warn('A dump::\n\n   reads 0x80\n'), [])

    def test_hex_warnings_do_not_fail_the_lint(self):
        text = GOOD_PART + '\nThe register reads ``0x0015`` after reset.\n'
        self.assertEqual(self.run_lint({'hardware/demo.rst': text}), [])

    def used_in(self, text):
        page = GOOD_PART.replace('Used in :ref:`sgi-ip30`.', text)
        return self.messages({'hardware/demo.rst': page})

    def test_used_in_names_catalogue_machines(self):
        for ok in ('Used in no machine.',
                   'Used in :ref:`sgi-ip27` (Origin 200, Onyx2 and Origin 200).',
                   'Used in :ref:`sgi-ip27`: the ``origin200`` and the\n'
                   '``origin200-dual`` machines.',
                   'Used in :ref:`sgi-ip27`; the ``onyx2-deskside`` topology.',
                   'Used in :ref:`sgi-ip27`. The ``sgi-demo`` device and the\n'
                   '``io7`` preset are not machines.'):
            self.assertEqual(self.used_in(ok), '', ok)

    def test_used_in_flags_unknown_machines(self):
        for bad, name in (
                ('Used in :ref:`sgi-ip27` (``origin2100``).', 'origin2100'),
                ('Used in the ``tezro9`` machine.', 'tezro9'),
                ('Used in the ``pc`` topology.', 'pc'),
                ('Used in the Origin 2100.', 'Origin 2100'),
                ('Used in the Onyx 9.', 'Onyx 9')):
            out = self.used_in(bad)
            self.assertIn(f'names ``{name}``' if name[0].islower()
                          else f'names "{name}"', out, bad)

    def test_used_in_reports_the_wrapped_line(self):
        out = self.used_in('Used in :ref:`sgi-ip27`, wrapped\n'
                           'and then ``origin9000``.')
        self.assertIn('hardware/demo.rst:10:', out)

    def test_used_in_without_catalogue_is_not_checked(self):
        page = GOOD_PART.replace('Used in :ref:`sgi-ip30`.', 'Used in ``origin9``.')
        self.assertEqual(
            self.run_lint({'hardware/demo.rst': page}, catalogue=None), [])

    def test_unlisted_page(self):
        out = self.messages({'hardware/demo.rst': GOOD_PART}, listed=False)
        self.assertIn('not listed in LICENSE.origami.paths', out)

    def test_current_pages_are_clean(self):
        self.assertEqual(lint.lint(SOURCE), [])


if __name__ == '__main__':
    unittest.main()
